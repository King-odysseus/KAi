// Builds KAI's file-type icon set from Material Icon Theme (MIT).
//
// Reads the theme's manifest, copies only the SVGs the manifest actually uses into
// src/renderer/public/file-icons/, and writes a compact lookup module next to the
// resolver. Run after bumping the `material-icon-theme` dev dependency:
//   node apps/desktop/scripts/generate-file-icons.mjs
// The output is committed, so a normal build never needs the dev dependency.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const packageRoot = path.dirname(require.resolve('material-icon-theme/package.json'));
const manifest = JSON.parse(fs.readFileSync(path.join(packageRoot, 'dist', 'material-icons.json'), 'utf8'));
const target = path.join(here, '..', 'src', 'renderer', 'src');
// In Vite's public dir so the SVGs ship as plain files: importing 1,200 small assets would inline them all into the JS bundle.
const iconsOut = path.join(here, '..', 'src', 'renderer', 'public', 'file-icons');

const used = new Set([manifest.file, manifest.folder, manifest.folderExpanded, manifest.rootFolder, manifest.rootFolderExpanded]);
const use = (id) => { used.add(id); return id; };

// Icons KAI's own resolver names in src/renderer/src/file-icons.ts (KAI_FILE_NAMES / KAI_FOLDER_NAMES),
// with the open-folder twins, so they ship even where the theme itself never maps a name to them.
for (const id of ['claude', 'robot', 'gemini-ai', 'skill', 'console', 'document']) used.add(id);
for (const id of ['folder-robot', 'folder-claude', 'folder-tasks', 'folder-skills', 'folder-resource', 'folder-backup', 'folder-docs']) {
  used.add(id);
  used.add(`${id}-open`);
}

const lower = (map) => Object.fromEntries(Object.entries(map).map(([key, id]) => [key.toLowerCase(), use(id)]));

const folderNames = lower(manifest.folderNames);
const folderOpen = {};
for (const [key, id] of Object.entries(manifest.folderNamesExpanded)) {
  const name = key.toLowerCase();
  // Almost every folder icon has an "-open" twin with a predictable name; only record the exceptions.
  if (id !== `${folderNames[name]}-open`) folderOpen[name] = use(id);
  else use(id);
}

const light = manifest.light ?? {};
const output = {
  fileNames: lower(manifest.fileNames),
  fileExtensions: lower(manifest.fileExtensions),
  folderNames,
  folderOpen,
  lightFileNames: lower(light.fileNames ?? {}),
  lightFileExtensions: lower(light.fileExtensions ?? {}),
  lightFolderNames: lower(light.folderNames ?? {}),
  lightFolderOpen: lower(light.folderNamesExpanded ?? {}),
  base: {
    file: manifest.file,
    folder: manifest.folder,
    folderOpen: manifest.folderExpanded,
    root: manifest.rootFolder,
    rootOpen: manifest.rootFolderExpanded,
  },
};

fs.rmSync(iconsOut, { recursive: true, force: true });
fs.mkdirSync(iconsOut, { recursive: true });
let copied = 0;
for (const id of used) {
  const definition = manifest.iconDefinitions[id];
  if (!definition) throw new Error(`manifest names icon "${id}" with no definition`);
  const file = path.basename(definition.iconPath);
  // A few icons are ".clone.svg" duplicates; every icon is written as <id>.svg so the resolver needs no table.
  fs.copyFileSync(path.join(packageRoot, 'icons', file), path.join(iconsOut, `${id}.svg`));
  copied += 1;
}
fs.copyFileSync(path.join(packageRoot, 'LICENSE'), path.join(iconsOut, 'LICENSE-material-icon-theme.txt'));

const banner = [
  '// GENERATED by apps/desktop/scripts/generate-file-icons.mjs from Material Icon Theme (MIT). Do not edit.',
  '// Keys are lower-case; values are icon ids that name a file in public/file-icons/<id>.svg.',
  '',
].join('\n');
const body = Object.entries(output)
  .map(([name, value]) => `export const ${name.replace(/^./, (c) => c.toUpperCase()).replace(/^/, 'ICON_')}: ${name === 'base' ? '{ file: string; folder: string; folderOpen: string; root: string; rootOpen: string }' : 'Readonly<Record<string, string>>'} = ${JSON.stringify(value)};\n`)
  .join('\n');
fs.writeFileSync(path.join(target, 'file-icons.generated.ts'), `${banner}\n${body}`);
console.log(`file icons: ${copied} svgs, ${Object.keys(output.fileNames).length} names, ${Object.keys(output.fileExtensions).length} extensions, ${Object.keys(output.folderNames).length} folders`);
